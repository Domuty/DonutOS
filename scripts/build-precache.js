// Writes src/precache-manifest.js: the list of files the service worker caches for offline
// use, and a version hash of their contents. Run after changing any file in /src
// (Vercel runs it automatically on deploy; `npm run dist` runs it before packaging).

'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const SRC = path.join(__dirname, '..', 'src');
const OUT = path.join(SRC, 'precache-manifest.js');
const SKIP = new Set(['sw.js', 'precache-manifest.js']);
// Store app sources aren't needed at runtime: the packaged .dapp files in store/catalog are.
const SKIP_DIRS = new Set(['tests', 'store/apps']);

function walk(dir, rel = '') {
  const out = [];
  for (const ent of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (ent.name.startsWith('.')) continue;
    const r = rel ? `${rel}/${ent.name}` : ent.name;
    if (ent.isDirectory()) { if (!SKIP_DIRS.has(r)) out.push(...walk(path.join(dir, ent.name), r)); }
    else if (!SKIP.has(r)) out.push(r);
  }
  return out;
}

// The version shown in DonutOS (Settings › About, the kernel) comes from package.json.
const pkg = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'package.json'), 'utf8'));
fs.writeFileSync(path.join(SRC, 'version.js'), `// Generated by scripts/build-precache.js from package.json — do not edit.\nexport const VERSION = ${JSON.stringify(pkg.version)};\n`);

const files = walk(SRC);
const hash = crypto.createHash('sha256');
for (const f of files) { hash.update(f); hash.update(fs.readFileSync(path.join(SRC, f))); }
const version = hash.digest('hex').slice(0, 12);
fs.writeFileSync(OUT, `// Generated by scripts/build-precache.js — do not edit.\nself.DONUT_PRECACHE = ${JSON.stringify({ version, files: ['./', ...files] }, null, 1)};\n`);
console.log(`precache: ${files.length} files, version ${version}`);
