// Builds src/shell/emoji-data.js from the emojibase-data package (MIT licence):
// `npm pack emojibase-data@16 && tar xzf emojibase-data-*.tgz`, then
// `node scripts/build-emoji.js path/to/package`.
// Emoji newer than Unicode Emoji 15.0 are left out so every entry renders on current systems.

'use strict';
const fs = require('node:fs');
const path = require('node:path');

const pkg = process.argv[2];
if (!pkg) { console.error('usage: node scripts/build-emoji.js <emojibase-data package dir>'); process.exit(1); }
const data = require(path.resolve(pkg, 'en/data.json'));
const GROUPS = ['Smileys & emotion', 'People & body', null, 'Animals & nature', 'Food & drink', 'Travel & places', 'Activities', 'Objects', 'Symbols', 'Flags'];

const out = GROUPS.map(() => []);
for (const e of data.sort((a, b) => a.order - b.order)) {
  if (e.group === undefined || GROUPS[e.group] === null || e.version > 15) continue;
  const words = [e.label, ...(e.tags || [])].join(' ').toLowerCase();
  const skins = e.group === 1 && e.skins ? e.skins.filter((s) => s.version <= 15).map((s) => s.emoji) : null;
  out[e.group].push(skins && skins.length === 5 ? [e.emoji, words, skins] : [e.emoji, words]);
}
const groups = GROUPS.map((name, i) => (name ? { name, items: out[i] } : null)).filter(Boolean);
const file = `// Generated by scripts/build-emoji.js from emojibase-data (MIT). Do not edit.
// Each item: [emoji, searchable words, skin-tone variants?]
export const EMOJI_GROUPS = ${JSON.stringify(groups)};
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'shell', 'emoji-data.js'), file);
console.log(`emoji: ${groups.reduce((n, g) => n + g.items.length, 0)} in ${groups.length} groups, ${(file.length / 1024).toFixed(0)} KB`);
